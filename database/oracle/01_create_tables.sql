-- =====================================================================
-- Reports Management System - tables (Oracle)
-- Oracle Database 12c or later (uses identity columns).
--
-- Step 2 of 3. Run as the schema owner the application connects with
-- (the RMS user from 00_create_user.sql), for example from SQL*Plus or
-- SQL Developer:   @01_create_tables.sql
--
-- "User" is a reserved word in Oracle, so every table carries the RMS_ prefix:
--   User            -> RMS_USERS
--   Application     -> RMS_APPLICATIONS
--   ReportsCategory -> RMS_REPORT_CATEGORIES
--   Reports         -> RMS_REPORTS
-- plus three supporting tables:
--   RMS_REPORT_PARAMETERS  optional label/type/dropdown settings per @parameter
--   RMS_USER_REPORTS       which user may run which report
--   RMS_REPORT_RUN_LOG     audit trail of report runs and exports
-- =====================================================================

CREATE TABLE RMS_USERS
(
    ID           NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CODE         VARCHAR2(50 CHAR)   NOT NULL,
    FULL_NAME    VARCHAR2(200 CHAR),
    EMAIL        VARCHAR2(256 CHAR),
    AD_USERNAME  VARCHAR2(100 CHAR)  NOT NULL,
    ACTIVE       NUMBER(1)           DEFAULT 1 NOT NULL,
    ROLE         VARCHAR2(20 CHAR)   DEFAULT 'Viewer' NOT NULL,
    CREATED_AT   TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP,
    CONSTRAINT PK_RMS_USERS PRIMARY KEY (ID),
    CONSTRAINT UK_RMS_USERS_CODE UNIQUE (CODE),
    CONSTRAINT CK_RMS_USERS_ACTIVE CHECK (ACTIVE IN (0, 1)),
    CONSTRAINT CK_RMS_USERS_ROLE CHECK (ROLE IN ('Admin', 'Viewer'))
);

-- AD account names are not case sensitive, so uniqueness is enforced on the upper-cased value.
CREATE UNIQUE INDEX UK_RMS_USERS_ADUSER ON RMS_USERS (UPPER(AD_USERNAME));

COMMENT ON TABLE  RMS_USERS             IS 'People allowed to sign in to Reports Management';
COMMENT ON COLUMN RMS_USERS.AD_USERNAME IS 'Active Directory sAMAccountName, without the domain';
COMMENT ON COLUMN RMS_USERS.ROLE        IS 'Admin or Viewer. Admin also requires membership of the admin AD group';


CREATE TABLE RMS_APPLICATIONS
(
    ID               NUMBER(10)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CODE             VARCHAR2(50 CHAR)    NOT NULL,
    NAME             VARCHAR2(200 CHAR)   NOT NULL,
    DESCRIPTION      VARCHAR2(1000 CHAR),
    ACTIVE           NUMBER(1)            DEFAULT 1 NOT NULL,
    CONNECTION_NAME  VARCHAR2(100 CHAR),
    CREATED_AT       TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP,
    CONSTRAINT PK_RMS_APPLICATIONS PRIMARY KEY (ID),
    CONSTRAINT UK_RMS_APPLICATIONS_CODE UNIQUE (CODE),
    CONSTRAINT CK_RMS_APPLICATIONS_ACTIVE CHECK (ACTIVE IN (0, 1))
);

COMMENT ON TABLE  RMS_APPLICATIONS                 IS 'Source systems that reports belong to';
COMMENT ON COLUMN RMS_APPLICATIONS.CONNECTION_NAME IS 'Name of the connection string its reports run on. NULL = default report connection. Never the connection string itself';


CREATE TABLE RMS_REPORT_CATEGORIES
(
    ID           NUMBER(10)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CODE         VARCHAR2(50 CHAR)    NOT NULL,
    NAME         VARCHAR2(200 CHAR)   NOT NULL,
    DESCRIPTION  VARCHAR2(1000 CHAR),
    ACTIVE       NUMBER(1)            DEFAULT 1 NOT NULL,
    CREATED_AT   TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP,
    CONSTRAINT PK_RMS_REPORT_CATEGORIES PRIMARY KEY (ID),
    CONSTRAINT UK_RMS_REPORT_CAT_CODE UNIQUE (CODE),
    CONSTRAINT CK_RMS_REPORT_CAT_ACTIVE CHECK (ACTIVE IN (0, 1))
);

COMMENT ON TABLE RMS_REPORT_CATEGORIES IS 'Groups of reports, shared across applications';


CREATE TABLE RMS_REPORTS
(
    ID                   NUMBER(10)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CODE                 VARCHAR2(50 CHAR)    NOT NULL,
    NAME                 VARCHAR2(200 CHAR)   NOT NULL,
    DESCRIPTION          VARCHAR2(1000 CHAR),
    APPLICATION_ID       NUMBER(10)           NOT NULL,
    REPORTS_CATEGORY_ID  NUMBER(10)           NOT NULL,
    SQL_QUERY            CLOB                 NOT NULL,
    QUERY_TYPE           VARCHAR2(20 CHAR)    DEFAULT 'Select' NOT NULL,
    ACTIVE               NUMBER(1)            DEFAULT 1 NOT NULL,
    CREATED_AT           TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP,
    CONSTRAINT PK_RMS_REPORTS PRIMARY KEY (ID),
    CONSTRAINT UK_RMS_REPORTS_CODE UNIQUE (CODE),
    CONSTRAINT FK_RMS_REPORTS_APPLICATION FOREIGN KEY (APPLICATION_ID) REFERENCES RMS_APPLICATIONS (ID),
    CONSTRAINT FK_RMS_REPORTS_CATEGORY FOREIGN KEY (REPORTS_CATEGORY_ID) REFERENCES RMS_REPORT_CATEGORIES (ID),
    CONSTRAINT CK_RMS_REPORTS_ACTIVE CHECK (ACTIVE IN (0, 1)),
    CONSTRAINT CK_RMS_REPORTS_QUERY_TYPE CHECK (QUERY_TYPE IN ('Select', 'StoredProcedure'))
);

CREATE INDEX IX_RMS_REPORTS_APPLICATION ON RMS_REPORTS (APPLICATION_ID);
CREATE INDEX IX_RMS_REPORTS_CATEGORY ON RMS_REPORTS (REPORTS_CATEGORY_ID);

COMMENT ON TABLE  RMS_REPORTS            IS 'Report definitions';
COMMENT ON COLUMN RMS_REPORTS.SQL_QUERY  IS 'SELECT statement (or procedure call) with @Name placeholders for parameters';
COMMENT ON COLUMN RMS_REPORTS.QUERY_TYPE IS 'Select = a single SELECT/WITH statement. StoredProcedure = package.procedure(..., @RMS_CURSOR)';


CREATE TABLE RMS_REPORT_PARAMETERS
(
    ID              NUMBER(10)          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    REPORT_ID       NUMBER(10)          NOT NULL,
    NAME            VARCHAR2(100 CHAR)  NOT NULL,
    LABEL           VARCHAR2(200 CHAR)  NOT NULL,
    DATA_TYPE       VARCHAR2(20 CHAR)   DEFAULT 'Text' NOT NULL,
    REQUIRED        NUMBER(1)           DEFAULT 1 NOT NULL,
    ALLOW_MULTIPLE  NUMBER(1)           DEFAULT 0 NOT NULL,
    DEFAULT_VALUE   VARCHAR2(500 CHAR),
    LOOKUP_SOURCE   CLOB,
    HELP_TEXT       VARCHAR2(500 CHAR),
    SORT_ORDER      NUMBER(5)           DEFAULT 0 NOT NULL,
    CONSTRAINT PK_RMS_REPORT_PARAMETERS PRIMARY KEY (ID),
    CONSTRAINT FK_RMS_REPORT_PARAMS_REPORT FOREIGN KEY (REPORT_ID) REFERENCES RMS_REPORTS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_RMS_REPORT_PARAMS_TYPE CHECK (DATA_TYPE IN ('Text', 'Integer', 'Decimal', 'Date', 'DateTime', 'Boolean')),
    CONSTRAINT CK_RMS_REPORT_PARAMS_REQUIRED CHECK (REQUIRED IN (0, 1)),
    CONSTRAINT CK_RMS_REPORT_PARAMS_MULTI CHECK (ALLOW_MULTIPLE IN (0, 1))
);

CREATE UNIQUE INDEX UK_RMS_REPORT_PARAMS_NAME ON RMS_REPORT_PARAMETERS (REPORT_ID, UPPER(NAME));

COMMENT ON TABLE  RMS_REPORT_PARAMETERS               IS 'Optional presentation settings for the @parameters of a report. A parameter with no row is a required text box';
COMMENT ON COLUMN RMS_REPORT_PARAMETERS.NAME          IS 'Parameter name as written in SQL_QUERY, without the @';
COMMENT ON COLUMN RMS_REPORT_PARAMETERS.DEFAULT_VALUE IS 'Literal, or for dates a token: TODAY, START_OF_MONTH, TODAY-7 ...';
COMMENT ON COLUMN RMS_REPORT_PARAMETERS.LOOKUP_SOURCE IS 'Makes the field a dropdown: a SELECT returning value,label or a fixed list like A=Active;I=Inactive';


CREATE TABLE RMS_USER_REPORTS
(
    USER_ID      NUMBER(10)          NOT NULL,
    REPORT_ID    NUMBER(10)          NOT NULL,
    ASSIGNED_AT  TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    ASSIGNED_BY  VARCHAR2(100 CHAR),
    CONSTRAINT PK_RMS_USER_REPORTS PRIMARY KEY (USER_ID, REPORT_ID),
    CONSTRAINT FK_RMS_USER_REPORTS_USER FOREIGN KEY (USER_ID) REFERENCES RMS_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_RMS_USER_REPORTS_REPORT FOREIGN KEY (REPORT_ID) REFERENCES RMS_REPORTS (ID) ON DELETE CASCADE
);

CREATE INDEX IX_RMS_USER_REPORTS_REPORT ON RMS_USER_REPORTS (REPORT_ID);

COMMENT ON TABLE RMS_USER_REPORTS IS 'Reports each user is allowed to run';


CREATE TABLE RMS_REPORT_RUN_LOG
(
    ID             NUMBER(18)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
    REPORT_ID      NUMBER(10),
    REPORT_NAME    VARCHAR2(200 CHAR),
    USER_ID        NUMBER(10),
    USERNAME       VARCHAR2(100 CHAR)   NOT NULL,
    RUN_AT         TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    ACTION         VARCHAR2(30 CHAR)    NOT NULL,
    DURATION_MS    NUMBER(12)           DEFAULT 0 NOT NULL,
    ROW_COUNT      NUMBER(10),
    SUCCESS        NUMBER(1)            DEFAULT 1 NOT NULL,
    ERROR_MESSAGE  VARCHAR2(1000 CHAR),
    PARAMETERS     CLOB,
    CONSTRAINT PK_RMS_REPORT_RUN_LOG PRIMARY KEY (ID),
    CONSTRAINT FK_RMS_RUN_LOG_REPORT FOREIGN KEY (REPORT_ID) REFERENCES RMS_REPORTS (ID) ON DELETE SET NULL,
    CONSTRAINT FK_RMS_RUN_LOG_USER FOREIGN KEY (USER_ID) REFERENCES RMS_USERS (ID) ON DELETE SET NULL,
    CONSTRAINT CK_RMS_RUN_LOG_SUCCESS CHECK (SUCCESS IN (0, 1))
);

CREATE INDEX IX_RMS_RUN_LOG_RUN_AT ON RMS_REPORT_RUN_LOG (RUN_AT);
CREATE INDEX IX_RMS_RUN_LOG_REPORT ON RMS_REPORT_RUN_LOG (REPORT_ID);
CREATE INDEX IX_RMS_RUN_LOG_USER ON RMS_REPORT_RUN_LOG (USER_ID);

COMMENT ON TABLE  RMS_REPORT_RUN_LOG             IS 'Who ran or exported which report, when, and with which parameter values';
COMMENT ON COLUMN RMS_REPORT_RUN_LOG.REPORT_NAME IS 'Name at the time of the run; kept after the report is deleted';
COMMENT ON COLUMN RMS_REPORT_RUN_LOG.ACTION      IS 'View, Export:xlsx, Export:pdf or Export:csv';
