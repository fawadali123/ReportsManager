-- =====================================================================
-- Reports Management System - add report scheduling (Oracle)
--
-- Only for a schema created BEFORE scheduling existed. A new installation
-- gets these tables from 01_create_tables.sql and does not need this script.
-- Run as the RMS schema owner:   @06_upgrade_add_scheduling.sql
-- =====================================================================

CREATE TABLE RMS_REPORT_SCHEDULES
(
    ID                 NUMBER(10)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
    REPORT_ID          NUMBER(10)           NOT NULL,
    NAME               VARCHAR2(200 CHAR)   NOT NULL,
    ACTIVE             NUMBER(1)            DEFAULT 1 NOT NULL,
    FREQUENCY          VARCHAR2(10 CHAR)    NOT NULL,
    RUN_TIME           VARCHAR2(5 CHAR),
    END_TIME           VARCHAR2(5 CHAR),
    INTERVAL_HOURS     NUMBER(2),
    DAYS_OF_WEEK       VARCHAR2(30 CHAR),
    DAY_OF_MONTH       NUMBER(2),
    RUN_ONCE_AT        TIMESTAMP,
    START_DATE         DATE,
    END_DATE           DATE,
    TIME_ZONE          VARCHAR2(64 CHAR)    NOT NULL,
    EXPORT_FORMAT      VARCHAR2(10 CHAR)    DEFAULT 'xlsx' NOT NULL,
    PARAMETER_VALUES   CLOB,
    SKIP_IF_EMPTY      NUMBER(1)            DEFAULT 0 NOT NULL,
    SEND_EMAIL         NUMBER(1)            DEFAULT 0 NOT NULL,
    EMAIL_TO           VARCHAR2(2000 CHAR),
    EMAIL_CC           VARCHAR2(2000 CHAR),
    EMAIL_SUBJECT      VARCHAR2(300 CHAR),
    EMAIL_BODY         VARCHAR2(4000 CHAR),
    SAVE_TO_SHARE      NUMBER(1)            DEFAULT 0 NOT NULL,
    SHARE_FOLDER       VARCHAR2(500 CHAR),
    FILE_NAME_PATTERN  VARCHAR2(200 CHAR),
    NEXT_RUN_UTC       TIMESTAMP,
    LAST_RUN_UTC       TIMESTAMP,
    LAST_STATUS        VARCHAR2(20 CHAR),
    RUN_REQUESTED_UTC  TIMESTAMP,
    RUN_REQUESTED_BY   VARCHAR2(100 CHAR),
    LOCKED_BY          VARCHAR2(100 CHAR),
    LOCKED_UNTIL_UTC   TIMESTAMP,
    CREATED_BY         VARCHAR2(100 CHAR),
    CREATED_AT         TIMESTAMP            DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY         VARCHAR2(100 CHAR),
    UPDATED_AT         TIMESTAMP,
    CONSTRAINT PK_RMS_REPORT_SCHEDULES PRIMARY KEY (ID),
    CONSTRAINT FK_RMS_SCHEDULES_REPORT FOREIGN KEY (REPORT_ID) REFERENCES RMS_REPORTS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_RMS_SCHEDULES_ACTIVE CHECK (ACTIVE IN (0, 1)),
    CONSTRAINT CK_RMS_SCHEDULES_FREQ CHECK (FREQUENCY IN ('Once', 'Hourly', 'Daily', 'Weekly', 'Monthly')),
    CONSTRAINT CK_RMS_SCHEDULES_SKIP CHECK (SKIP_IF_EMPTY IN (0, 1)),
    CONSTRAINT CK_RMS_SCHEDULES_EMAIL CHECK (SEND_EMAIL IN (0, 1)),
    CONSTRAINT CK_RMS_SCHEDULES_SHARE CHECK (SAVE_TO_SHARE IN (0, 1))
);

CREATE INDEX IX_RMS_SCHEDULES_DUE ON RMS_REPORT_SCHEDULES (ACTIVE, NEXT_RUN_UTC);
CREATE INDEX IX_RMS_SCHEDULES_REPORT ON RMS_REPORT_SCHEDULES (REPORT_ID);

COMMENT ON TABLE  RMS_REPORT_SCHEDULES                  IS 'Reports generated automatically by the RMS Scheduler service';
COMMENT ON COLUMN RMS_REPORT_SCHEDULES.FREQUENCY        IS 'Once, Hourly, Daily, Weekly or Monthly';
COMMENT ON COLUMN RMS_REPORT_SCHEDULES.RUN_TIME         IS 'HH:mm in TIME_ZONE. Hourly: first run of the day';
COMMENT ON COLUMN RMS_REPORT_SCHEDULES.END_TIME         IS 'Hourly only: no runs after this HH:mm';
COMMENT ON COLUMN RMS_REPORT_SCHEDULES.DAYS_OF_WEEK     IS 'Comma list such as Sun,Mon,Tue. Required for Weekly, optional filter for Hourly and Daily';
COMMENT ON COLUMN RMS_REPORT_SCHEDULES.DAY_OF_MONTH     IS 'Monthly: 1-31, or 0 for the last day of the month';
COMMENT ON COLUMN RMS_REPORT_SCHEDULES.RUN_ONCE_AT      IS 'Once: local date and time in TIME_ZONE';
COMMENT ON COLUMN RMS_REPORT_SCHEDULES.PARAMETER_VALUES IS 'JSON object of parameter name to list of values; dates may be tokens such as START_OF_PREV_MONTH';
COMMENT ON COLUMN RMS_REPORT_SCHEDULES.NEXT_RUN_UTC     IS 'When the scheduler runs it next, in UTC';
COMMENT ON COLUMN RMS_REPORT_SCHEDULES.LOCKED_BY        IS 'Scheduler instance running it now; stops two services running the same schedule';


CREATE TABLE RMS_SCHEDULE_RUNS
(
    ID                 NUMBER(18)           GENERATED BY DEFAULT ON NULL AS IDENTITY,
    SCHEDULE_ID        NUMBER(10),
    SCHEDULE_NAME      VARCHAR2(200 CHAR)   NOT NULL,
    REPORT_ID          NUMBER(10),
    REPORT_NAME        VARCHAR2(200 CHAR),
    TRIGGER_TYPE       VARCHAR2(10 CHAR)    NOT NULL,
    SCHEDULED_FOR_UTC  TIMESTAMP,
    STARTED_UTC        TIMESTAMP            NOT NULL,
    FINISHED_UTC       TIMESTAMP,
    STATUS             VARCHAR2(20 CHAR)    NOT NULL,
    ROW_COUNT          NUMBER(10),
    TRUNCATED          NUMBER(1)            DEFAULT 0 NOT NULL,
    FILE_NAME          VARCHAR2(260 CHAR),
    FILE_SIZE          NUMBER(12),
    EMAIL_RESULT       VARCHAR2(1000 CHAR),
    SHARE_RESULT       VARCHAR2(1000 CHAR),
    ERROR_MESSAGE      VARCHAR2(2000 CHAR),
    MACHINE_NAME       VARCHAR2(100 CHAR),
    CONSTRAINT PK_RMS_SCHEDULE_RUNS PRIMARY KEY (ID),
    CONSTRAINT FK_RMS_SCHEDULE_RUNS_SCHEDULE FOREIGN KEY (SCHEDULE_ID) REFERENCES RMS_REPORT_SCHEDULES (ID) ON DELETE SET NULL,
    CONSTRAINT CK_RMS_SCHEDULE_RUNS_TRUNC CHECK (TRUNCATED IN (0, 1))
);

CREATE INDEX IX_RMS_SCHEDULE_RUNS_SCHEDULE ON RMS_SCHEDULE_RUNS (SCHEDULE_ID, STARTED_UTC);
CREATE INDEX IX_RMS_SCHEDULE_RUNS_STARTED ON RMS_SCHEDULE_RUNS (STARTED_UTC);

COMMENT ON TABLE  RMS_SCHEDULE_RUNS              IS 'One row per scheduled or manual run of a schedule, kept after the schedule is deleted';
COMMENT ON COLUMN RMS_SCHEDULE_RUNS.TRIGGER_TYPE IS 'Schedule or Manual (Run now)';
COMMENT ON COLUMN RMS_SCHEDULE_RUNS.STATUS       IS 'Running, Succeeded, Partial (one delivery failed), Failed or Skipped (no rows)';
